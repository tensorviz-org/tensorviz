#!/usr/bin/env node
/** Python owns validation policy. Generate/check structural types and schema. */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

function contractPython() {
  if (process.env.PYTHON) return process.env.PYTHON;
  for (const relative of ['venv/bin/python', '.venv/bin/python']) {
    const candidate = join(root, relative);
    if (existsSync(candidate)) return candidate;
  }
  console.error(
    "No Python was selected for contract generation. Set PYTHON to an interpreter that can import pydantic, or create ./venv or ./.venv and install the contract dependency: python3.12 -m venv .venv && .venv/bin/pip install 'pydantic>=2.12,<3'",
  );
  process.exit(1);
}

const python = contractPython();
try {
  execFileSync(python, ['-c', 'import pydantic'], { stdio: 'pipe' });
} catch {
  console.error(`${python} cannot import pydantic. Install the contract dependency with: ${python} -m pip install 'pydantic>=2.12,<3'`);
  process.exit(1);
}

const contract = process.argv.includes('--semantic') ? 'semantic' : 'validation';
const temp = mkdtempSync(join(tmpdir(), `tensorviz-${contract}-contracts-`));
try {
  const schema = join(temp, 'schema.json');
  const openapi = join(temp, 'openapi.json');
  execFileSync(python, [
    resolve(root, 'backend/scripts/export_validation_contracts.py'), '--schema', schema, '--openapi', openapi,
    '--contract', contract,
  ], { env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' } });
  // Python's required list owns optionality, including fields with defaults.
  const generated = astToString(await openapiTS(JSON.parse(readFileSync(openapi, 'utf8')), { defaultNonNullable: false }));
  const types = `/* GENERATED from backend/services/${contract}/contracts.py; npm run ${contract}:generate from the repository root. */\n` + generated;
  const outputs = [
    [`packages/contracts/src/${contract}Contracts.generated.ts`, types],
  ];
  if (contract === 'semantic') {
    outputs.push(['canvas/src/types/semanticContracts.generated.ts', types]);
    outputs.push(['packages/contracts/src/semanticSchema.generated.ts',
      '/* GENERATED from services/semantic/contracts.py; npm run semantic:generate. */\n' +
      'const schema: object = ' + readFileSync(schema, 'utf8').trim() + ';\nexport default schema;\n']);
    // The offline viewer forbids unsafe-eval. Compile validators here, never in
    // the user's browser. Runtime imports are limited to Ajv's pure helpers.
    const ajv = new Ajv({ strict: false, ownProperties: true, code: { source: true, esm: true, lines: true } });
    ajv.addSchema(JSON.parse(readFileSync(schema, 'utf8')), 'semantic');
    const validators = standaloneCode(ajv, Object.fromEntries(['PortableCapture', 'CaptureReference', 'DisplayPort', 'ProjectionEdge']
      .map(name => [`is${name}`, `semantic#/definitions/${name}`])));
    outputs.push(['canvas/src/types/portableValidators.generated.ts',
      '/* GENERATED by tooling/contracts/generate.mjs from the Python semantic schema. */\n' +
      '// @ts-nocheck — Ajv standalone validator output, compiled at build time for CSP.\n/* eslint-disable */\n' + validators]);
  } else {
    outputs.push([`tests/fixtures/contracts/${contract}.schema.json`, readFileSync(schema, 'utf8')]);
  }
  for (const [path, output] of outputs) {
    const target = resolve(root, path);
    if (process.argv.includes('--check')) {
      if (readFileSync(target, 'utf8') !== output) {
        throw new Error(`Outdated ${path}; from the repository root run npm run ${contract}:generate`);
      }
    } else writeFileSync(target, output);
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
